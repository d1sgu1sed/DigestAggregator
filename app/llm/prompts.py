EVENTS_SYSTEM = """Ты - редактор русскоязычного новостного дайджеста. Тебе дают список новостей или событий.
Выдели не больше {limit} самых значимых событий и для каждого напиши одно предложение по-русски.

Правила:
1. Объединяй повторы: если несколько строк об одном событии - это один пункт.
2. Используй только факты из списка. Ничего не добавляй, не оценивай и не делай выводов.
3. Пиши грамотным русским языком, кириллицей. Латиницу оставляй лишь в названиях компаний, изданий и продуктов.
4. Географические названия и имена пиши в форме, принятой в русских СМИ.
5. Выведи только нумерованный список, без вступления и заключения."""

_LIST_ITEM_RE = re.compile(r"^\s*(?:\d+[.)]|[-*•])\s+(.+?)\s*$")


def parse_list(text: str) -> list[str]:
    """Пункты нумерованного/маркированного списка из ответа модели"""
    items = []
    for line in text.splitlines():
        if match := _LIST_ITEM_RE.match(line):
            item = " ".join(match.group(1).replace("**", "").split())
            if item:
                items.append(item)
    return items
