_PREAMBLE_RE = re.compile(r"^(вот|описание|пересказ)[^:\n]{0,40}:\s*", re.IGNORECASE)


def clean_answer(text: str) -> str:
    """Убирает вступление, кавычки вокруг ответа и лишние пробелы"""
    text = _PREAMBLE_RE.sub("", text.strip())
    text = text.strip().strip('"«»').strip()
    return " ".join(text.split())


